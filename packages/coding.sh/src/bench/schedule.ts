// Daily runs: a cron line and a GitHub Actions workflow. Printing is the
// default; the crontab is only edited with an explicit --install-cron, and
// then only our own marked line is added or replaced.
import { spawnSync } from "node:child_process";
import { join } from "node:path";
import { benchHome } from "./define.ts";

export interface ScheduleOpts {
  name: string;
  /** HH:MM, local time for cron, UTC for Actions. Default 06:15. */
  at?: string;
  /** Directory the run starts in (where ./bench/<name>.toml is found). */
  cwd: string;
  /** How to invoke coding.sh (absolute paths survive cron's bare PATH). */
  cli: string[];
  env?: NodeJS.ProcessEnv;
  /** Also write the report here after each run. */
  reportDir?: string;
  /** Actions runner label(s). Default self-hosted. */
  runner?: string;
  /** coding.sh version the workflow installs (pinned, so a release can't change a running benchmark). */
  version?: string;
  /** Env vars the definition reads (tokenEnv, apiKeyEnv, headerEnv…); each becomes a secrets.* entry. */
  secrets?: string[];
}

/** Env var names a definition reads: every *Env string field and headerEnv values, anywhere in the tree. */
export function envRefs(def: unknown): string[] {
  const out = new Set<string>();
  const walk = (v: unknown, key = ""): void => {
    if (Array.isArray(v)) return v.forEach((x) => walk(x));
    if (!v || typeof v !== "object") {
      if (typeof v === "string" && /Env$/.test(key) && /^[A-Z_][A-Z0-9_]*$/.test(v)) out.add(v);
      return;
    }
    for (const [k, x] of Object.entries(v)) {
      if (k === "headerEnv" && x && typeof x === "object") {
        for (const name of Object.values(x)) if (typeof name === "string" && /^[A-Z_][A-Z0-9_]*$/.test(name)) out.add(name);
      } else walk(x, k);
    }
  };
  walk(def);
  return [...out].sort();
}

export function parseAt(at = "06:15"): { h: number; m: number } {
  const m = /^(\d{1,2}):(\d{2})$/.exec(at.trim());
  if (!m || Number(m[1]) > 23 || Number(m[2]) > 59) throw new Error(`--at must be HH:MM (24h), got ${JSON.stringify(at)}`);
  return { h: Number(m[1]), m: Number(m[2]) };
}

/** POSIX single-quoting. */
export function shq(s: string): string {
  return /^[\w@%+=:,./-]+$/.test(s) ? s : `'${s.replace(/'/g, `'\\''`)}'`;
}

export const cronMarker = (name: string) => `# coding.sh bench ${name}`;

export function cronLine(o: ScheduleOpts): string {
  const { h, m } = parseAt(o.at);
  const cli = o.cli.map(shq).join(" ");
  const log = join(benchHome(o.env), o.name, "cron.log");
  const report = o.reportDir ? ` && ${cli} bench report ${shq(o.name)} --out ${shq(o.reportDir)}` : "";
  return `${m} ${h} * * * cd ${shq(o.cwd)} && ${cli} bench run ${shq(o.name)}${report} >> ${shq(log)} 2>&1 ${cronMarker(o.name)}`;
}

export function workflowYaml(o: ScheduleOpts): string {
  const { h, m } = parseAt(o.at);
  const labels = (o.runner ?? "self-hosted").split(",").map((s) => s.trim()).filter(Boolean);
  const selfHosted = labels.includes("self-hosted");
  const runsOn = labels.length === 1 ? labels[0]! : `[${labels.join(", ")}]`;
  const report = o.reportDir ?? "bench-report";
  const runs = `~/.coding.sh/benchmarks/${o.name}`;
  // Run records are the benchmark's history and freshness ledger. A self-hosted runner keeps
  // them on disk; a hosted runner starts empty, so restore them from the last successful
  // run's artifact (artifacts aren't evicted like the cache, and every run re-uploads the
  // whole folder, so retention restarts daily).
  const restore = selfHosted
    ? ""
    : `      - name: Restore run history
        env:
          GH_TOKEN: \${{ github.token }}
        run: |
          id=$(gh run list --workflow "\${{ github.workflow }}" --status success --limit 1 --json databaseId --jq '.[0].databaseId // empty')
          mkdir -p ${runs}
          if [ -n "$id" ]; then gh run download "$id" --name bench-${o.name}-runs --dir ${runs}; fi
`;
  const secrets = o.secrets ?? [];
  const env = secrets.length
    ? `    env:
      # Secrets the definition reads. Add your contenders' API keys here too.
${secrets.map((k) => `      ${k}: \${{ secrets.${k} }}`).join("\n")}
`
    : `    # Contender API keys go here, from repository secrets:
    # env:
    #   EXAMPLE_API_KEY: \${{ secrets.EXAMPLE_API_KEY }}
`;
  const pkg = o.version ? `coding.sh@${o.version}` : "coding.sh";
  return `# Daily ${o.name} benchmark. Generated by: coding.sh bench schedule ${o.name}
name: bench-${o.name}
on:
  schedule:
    - cron: "${m} ${h} * * *"   # UTC
  workflow_dispatch: {}
concurrency:
  group: bench-${o.name}
  cancel-in-progress: false
permissions:
  contents: read
  actions: read
jobs:
  bench:
    runs-on: ${runsOn}
    timeout-minutes: 180
${env}    steps:
      - uses: actions/checkout@v4
      - uses: actions/setup-node@v4
        with:
          node-version: 22
${restore}      - name: Install coding.sh
        run: npm install -g ${pkg}
      - name: Run
        run: coding.sh bench run ${o.name}
      - name: Report
        if: always()
        run: coding.sh bench report ${o.name} --out ${report}
      - name: Keep run history
        if: always()
        uses: actions/upload-artifact@v4
        with:
          name: bench-${o.name}-runs
          path: ${runs}
          retention-days: 90
          include-hidden-files: true
      - uses: actions/upload-artifact@v4
        if: always()
        with:
          name: bench-${o.name}-report
          path: ${report}
`;
}

export interface CrontabIo {
  read(): string;
  write(text: string): void;
}

/** The real crontab via `crontab -l` / `crontab -`. */
export function systemCrontab(env: NodeJS.ProcessEnv = process.env): CrontabIo {
  return {
    read() {
      const r = spawnSync("crontab", ["-l"], { encoding: "utf8", env });
      if (r.error) throw new Error(`crontab is not available: ${r.error.message}`);
      // "no crontab for user" exits 1 with nothing on stdout: an empty table.
      return r.status === 0 ? r.stdout : "";
    },
    write(text) {
      const r = spawnSync("crontab", ["-"], { input: text, encoding: "utf8", env });
      if (r.error || r.status !== 0) throw new Error(`crontab - failed: ${r.error?.message ?? r.stderr.trim()}`);
    },
  };
}

/** Add or replace this benchmark's marked line; every other line is kept as is. */
export function mergeCrontab(current: string, line: string, name: string): { text: string; replaced: boolean } {
  const marker = cronMarker(name);
  const lines = current.split("\n");
  if (lines.at(-1) === "") lines.pop();
  const kept = lines.filter((l) => !l.endsWith(marker));
  return { text: [...kept, line].join("\n") + "\n", replaced: kept.length !== lines.length };
}

export function installCron(io: CrontabIo, line: string, name: string): { replaced: boolean; changed: boolean } {
  const cur = io.read();
  const { text, replaced } = mergeCrontab(cur, line, name);
  const changed = text !== (cur.endsWith("\n") || cur === "" ? cur : cur + "\n");
  if (changed) io.write(text);
  return { replaced, changed };
}
