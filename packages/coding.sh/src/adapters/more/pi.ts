const ID = "pi";
const MARKER = "@codingsh-pi-extension";
const EXT_FILE = "coding-sh.ts";

export function piAgentDir(env: NodeJS.ProcessEnv = process.env): string {
  return env.PI_CODING_AGENT_DIR || join(home(env), ".pi", "agent");
}

export function piSessionsDir(env: NodeJS.ProcessEnv = process.env): string {
  return env.PI_CODING_AGENT_SESSION_DIR || join(piAgentDir(env), "sessions");
}

export function piExtensionPath(opts: { scope: "user" | "project"; projectDir?: string | undefined }, env: NodeJS.ProcessEnv = process.env): string {
  if (opts.scope === "project") return join(opts.projectDir ?? process.cwd(), ".pi", "extensions", EXT_FILE);
  return join(piAgentDir(env), "extensions", EXT_FILE);
}

export function piExtensionSource(hookCommand: string, nodePath: string = resolveNodePath()): string {
  return `// ${MARKER} — generated by coding.sh; \`coding.sh uninstall pi\` removes it.
// Forwards Pi events to the local coding.sh spool. Records only; never blocks or modifies.
import { spawn } from "node:child_process";

const HOOK = ${JSON.stringify(hookCommand)};
const NODE = ${JSON.stringify(nodePath)};

export default function (pi: any) {
	const args = new Map<string, unknown>();
	const base = (ctx: any) => {
		const sm = ctx?.sessionManager;
		let sessionId: string | undefined;
		let sessionFile: string | undefined;
		try { sessionId = sm?.getSessionId?.(); } catch {}
		try { sessionFile = sm?.getSessionFile?.(); } catch {}
		const m = ctx?.model;
		return { sessionId, sessionFile, cwd: ctx?.cwd ?? process.cwd(), model: m ? { provider: m.provider, id: m.id } : undefined, mode: ctx?.mode };
	};
	const send = (event: string, payload: unknown, ctx: any): Promise<void> =>
		new Promise((resolve) => {
			let body: string;
			try {
				body = JSON.stringify({ ...(payload as object), ...base(ctx), hook_event_name: event, ts: Date.now() });
			} catch {
				return resolve();
			}
			const go = (bin: string, retry: boolean) => {
				try {
					const child = spawn(bin, [HOOK, "pi", event], { stdio: ["pipe", "ignore", "ignore"], env: process.env });
					child.on("error", () => (retry ? go("node", false) : resolve()));
					child.on("close", () => resolve());
					child.stdin?.on("error", () => {});
					child.stdin?.end(body);
				} catch {
					if (retry) go("node", false);
					else resolve();
				}
			};
			go(NODE, true);
			const t = setTimeout(resolve, 3000);
			(t as any)?.unref?.();
		});
	pi.on("session_start", (e: any, ctx: any) => { void send("session_start", { reason: e?.reason }, ctx); });
	pi.on("message_end", (e: any, ctx: any) => {
		const role = e?.message?.role;
		if (role === "user" || role === "assistant") void send("message_end", { message: e.message }, ctx);
	});
	pi.on("tool_execution_start", (e: any, ctx: any) => {
		if (e?.toolCallId) args.set(e.toolCallId, e.args);
		void send("tool_execution_start", e, ctx);
	});
	pi.on("tool_execution_end", (e: any, ctx: any) => {
		const a = e?.toolCallId ? args.get(e.toolCallId) : undefined;
		if (e?.toolCallId) args.delete(e.toolCallId);
		void send("tool_execution_end", { ...e, args: a }, ctx);
	});
	pi.on("session_compact", (e: any, ctx: any) => {
		void send("session_compact", { reason: e?.reason, willRetry: e?.willRetry, tokensBefore: e?.compactionEntry?.tokensBefore }, ctx);
	});
	pi.on("model_select", (e: any, ctx: any) => {
		void send("model_select", { source: e?.source, selected: e?.model ? { provider: e.model.provider, id: e.model.id } : undefined }, ctx);
	});
	// Awaited so the run's last events are flushed before \`pi -p\` / \`--mode json\` exits.
	pi.on("agent_settled", async (e: any, ctx: any) => { await send("agent_settled", { aborted: !!e?.aborted }, ctx); });
	pi.on("session_shutdown", async (e: any, ctx: any) => { await send("session_shutdown", { reason: e?.reason }, ctx); });
}
`;
}

const isOurs = (t: string | undefined): boolean => !!t && t.includes(MARKER);

/** Text of a Pi message content (string or [{type:"text",text}]). */
function contentText(c: unknown): string {
  if (typeof c === "string") return c;
  if (!Array.isArray(c)) return "";
  return c
    .filter((b) => isObj(b) && b.type === "text" && typeof b.text === "string")
    .map((b) => (b as Json).text as string)
    .join("\n");
}

function piUsage(u: unknown): Usage | undefined {
  if (!isObj(u)) return undefined;
  return usageFrom({ input: u.input, output: u.output, cacheRead: u.cacheRead, cacheWrite: num(u.cacheWrite) !== undefined || num(u.cacheWrite1h) !== undefined ? (num(u.cacheWrite) ?? 0) + (num(u.cacheWrite1h) ?? 0) : undefined, costUsd: get(u, "cost", "total") });
}

/**
 * Natural key of a Pi message: its creation time, which the extension's message_end
 * and the session file's entry carry alike (message_end has no entry id).
 */
const messageKey = (msg: Json): EventExtra => (num(msg.timestamp) !== undefined ? { key: ["msg", num(msg.timestamp)!] } : {});

/** Message entries of a session file: entry id, time, and whether the entry ends a turn. */
function piMessageEntries(file: string): { id: string; ts: number; final: boolean }[] {
  return jsonlTail("pi-messages", file, (e) => {
    if (e.type !== "message" || !isObj(e.message) || !str(e.id)) return [];
    const stop = str(e.message.stopReason);
    return [{ id: str(e.id)!, ts: toMs(e.timestamp) ?? 0, final: e.message.role === "assistant" && !!stop && stop !== "toolUse" }];
  });
}

/**
 * The session-file entry that ended the run settling at `ts` (agent_settled names none):
 * the last message entry written by then, when it is a reply that ends a turn. The
 * session file keys its turn.end by the same entry, so the two copies dedupe.
 */
export function piTurnEntry(file: string | undefined, ts: number): string | undefined {
  if (!file) return undefined;
  let last: { id: string; final: boolean } | undefined;
  for (const e of piMessageEntries(file)) if (e.ts <= ts) last = e;
  return last?.final ? last.id : undefined;
}

/** llm.call + assistant.message for a Pi assistant message. */
async function emitAssistant(em: Emitter, ctx: NormalizeContext, msg: Json, provider: string | undefined, requestModel: string | undefined, extra: EventExtra = {}, durationMs?: number): Promise<string | undefined> {
  const model = str(msg.responseModel) ?? str(msg.model) ?? requestModel;
  const usage = piUsage(msg.usage);
  const stop = str(msg.stopReason);
  em.push(
    "llm.call",
    { provider: str(msg.provider) ?? provider, requestModel: str(msg.model) ?? requestModel, responseModel: str(msg.responseModel) ?? str(msg.model), stopReason: stop, ok: stop !== "error", error: str(msg.errorMessage) },
    { ...extra, ...(model ? { model } : {}), ...(usage ? { usage } : {}), ...(durationMs !== undefined ? { durationMs } : {}) },
  );
  const text = contentText(msg.content).trim();
  if (text) await emitText(em, ctx, "assistant.message", text, { ...extra, ...(model ? { model } : {}) });
  return model;
}

export async function normalizePi(line: SpoolLine, ctx: NormalizeContext): Promise<AgentEvent[]> {
  if (isWrapperEvent(line.event)) return normalizeWrapperLine(line, ctx);
  const raw: Json = isObj(line.raw) ? line.raw : {};
  const sessionId = str(raw.sessionId) ?? `pi-unknown-${line.ppid ?? line.pid}`;
  const cwd = str(raw.cwd) ?? line.cwd;
  const ts = toMs(raw.ts) ?? line.ts;
  const provider = str(get(raw, "model", "provider"));
  const modelId = str(get(raw, "model", "id"));
  const em = new Emitter(ctx, { agent: ID, sessionId, ts, cwd, runId: line.runId, model: modelId }, spoolIdParts(line, sessionId, ctx), { toolKeys: true });
  const ev = str(raw.hook_event_name) ?? line.event;
  switch (ev) {
    case "session_start":
      em.push("session.start", { reason: str(raw.reason), sessionFile: str(raw.sessionFile), provider, source: "extension" });
      break;
    case "message_end": {
      const msg = isObj(raw.message) ? raw.message : {};
      const mts = toMs(msg.timestamp);
      const extra = { ...(mts ? { ts: mts } : {}), ...messageKey(msg) };
      if (msg.role === "user") {
        const text = contentText(msg.content).trim();
        if (text) await emitText(em, ctx, "user.message", text, extra);
      } else if (msg.role === "assistant") {
        // message.timestamp is when the response started streaming; message_end fires when it is done.
        await emitAssistant(em, ctx, msg, provider, modelId, extra, mts !== undefined && ts > mts ? ts - mts : undefined);
      }
      break;
    }
    case "tool_execution_start": {
      const tool = str(raw.toolName) ?? "unknown";
      await emitToolStart(em, ctx, tool, str(raw.toolCallId), raw.args);
      break;
    }
    case "tool_execution_end": {
      const tool = str(raw.toolName) ?? "unknown";
      const ok = raw.isError !== true;
      const output = get(raw, "result", "content") ?? raw.result;
      await emitToolEnd(em, ctx, { tool, toolUseId: str(raw.toolCallId), input: raw.args, output, ok, durationMs: num(raw.durationMs), error: ok ? undefined : "tool error" }, cwd);
      break;
    }
    case "session_compact":
      em.push("context.compact", { trigger: raw.reason === "manual" ? "manual" : "auto", reason: str(raw.reason), tokensBefore: num(raw.tokensBefore) });
      break;
    case "model_select":
      em.push("notification", { kind: "model_select", provider: str(get(raw, "selected", "provider")), model: str(get(raw, "selected", "id")), source: str(raw.source) });
      break;
    case "agent_settled":
      em.turnEnd({ aborted: raw.aborted === true }, piTurnEntry(str(raw.sessionFile), ts));
      break;
    case "session_shutdown":
      em.push("session.end", { reason: str(raw.reason) });
      break;
    default:
      em.push("notification", { kind: ev });
  }
  return attachRaw(em.events, await rawBlob(ctx, line.raw));
}

/** Events from one Pi session file. */
export async function* piSessionEvents(file: string, ctx: NormalizeContext, since?: number): AsyncGenerator<AgentEvent> {
  let sessionId: string | undefined;
  let cwd: string | undefined;
  let provider: string | undefined;
  let model: string | undefined;
  const calls = new Map<string, { tool: string; input: unknown; ts: number }>();
  for await (const { lineNo, value: e } of readJsonl(file)) {
    const ts = toMs(e.timestamp) ?? toMs(get(e, "message", "timestamp")) ?? mtimeMs(file);
    if (e.type === "session") {
      sessionId = str(e.id);
      cwd = str(e.cwd);
    }
    if (!sessionId) continue;
    const em = new Emitter(ctx, { agent: ID, sessionId, ts, cwd, model }, ["pi-file", sessionId, str(e.id) ?? lineNo], { toolKeys: true });
    if (e.type === "session") {
      em.push("session.start", { source: "transcript", version: num(e.version), parentSession: str(e.parentSession), file });
    } else if (e.type === "model_change") {
      provider = str(e.provider) ?? provider;
      model = str(e.modelId) ?? model;
      em.push("notification", { kind: "model_change", provider, model }, model ? { model } : {});
    } else if (e.type === "compaction") {
      em.push("context.compact", { trigger: "auto", tokensBefore: num(e.tokensBefore) });
    } else if (e.type === "message" && isObj(e.message)) {
      const msg = e.message;
      if (msg.role === "user") {
        const text = contentText(msg.content).trim();
        if (text) await emitText(em, ctx, "user.message", text, messageKey(msg));
      } else if (msg.role === "assistant") {
        const start = toMs(msg.timestamp);
        const done = toMs(e.timestamp);
        model = (await emitAssistant(em, ctx, msg, provider, model, messageKey(msg), start !== undefined && done !== undefined && done > start ? done - start : undefined)) ?? model;
        provider = str(msg.provider) ?? provider;
        for (const b of Array.isArray(msg.content) ? msg.content.filter(isObj) : []) {
          if (b.type !== "toolCall") continue;
          const tool = str(b.name) ?? "unknown";
          const id = str(b.id);
          if (id) calls.set(id, { tool, input: b.arguments, ts });
          await emitToolStart(em, ctx, tool, id, b.arguments);
        }
        const stop = str(msg.stopReason);
        if (stop && stop !== "toolUse") em.turnEnd({ stopReason: stop }, str(e.id));
      } else if (msg.role === "toolResult") {
        const id = str(msg.toolCallId);
        const call = id ? calls.get(id) : undefined;
        const tool = str(msg.toolName) ?? call?.tool ?? "unknown";
        const ok = msg.isError !== true;
        await emitToolEnd(em, ctx, { tool, toolUseId: id, input: call?.input, output: msg.content, ok, durationMs: call ? Math.max(0, ts - call.ts) || undefined : undefined }, cwd);
      } else if (msg.role === "bashExecution") {
        const command = str(msg.command);
        const id = `bash-${str(e.id) ?? lineNo}`;
        await emitToolStart(em, ctx, "user_bash", id, { command });
        await emitToolEnd(em, ctx, { tool: "user_bash", toolUseId: id, input: { command }, output: msg.output, ok: (num(msg.exitCode) ?? 0) === 0 }, cwd);
      }
    }
    for (const ev of em.events) if (since === undefined || ev.ts >= since) yield ev;
  }
}

export const piAdapter: Adapter = {
  id: ID,
  displayName: "Pi",
  tier: "A",
  // 2 (0.1.2): hook and transcript copies share ids; tokens counted once.
  // 3 (0.1.5): a tool call that loads a skill names it (payload.skill).
  parseVersion: 3,
  async detect(): Promise<DetectResult> {
    const binary = findBinary(["pi"]);
    const dir = piAgentDir();
    const r: DetectResult = { installed: !!binary || existsSync(dir), hooked: isOurs(readText(piExtensionPath({ scope: "user" }))) };
    if (binary) {
      r.binary = binary;
      const v = await binVersion(binary);
      if (v) r.version = v;
    }
    if (existsSync(dir)) r.configDir = dir;
    return r;
  },
  async install(opts: InstallOpts): Promise<FileChange[]> {
    const path = piExtensionPath(opts);
    const before = readText(path);
    if (before !== undefined && !isOurs(before)) throw new Error(`${path} exists and was not written by coding.sh; refusing to overwrite it`);
    const changes = applyWrites(ID, [{ path, before, after: piExtensionSource(opts.hookCommand, resolveNodePath(process.env)), summary: `${before ? "update" : "add"} Pi extension that records events to coding.sh`, mode: 0o644 }], opts.dryRun);
    if (opts.scope === "project")
      for (const c of changes) c.summary += " (project extensions load headless only when the project is trusted or with --approve)";
    return changes;
  },
  async uninstall(opts): Promise<FileChange[]> {
    const path = piExtensionPath(opts);
    const before = readText(path);
    if (!isOurs(before)) return [];
    return applyWrites(ID, [{ path, before, after: undefined, summary: "remove the coding.sh Pi extension" }], opts.dryRun);
  },
  normalize: normalizePi,
  async *backfill(ctx: NormalizeContext, opts?: { since?: number }): AsyncIterable<AgentEvent> {
    const dir = piSessionsDir();
    for (const f of walkFiles(dir, (n) => n.endsWith(".jsonl"), 2)) {
      if (opts?.since !== undefined && mtimeMs(f) < opts.since) continue;
      yield* piSessionEvents(f, ctx, opts?.since);
    }
  },
  async run(spec: RunSpec): Promise<AgentRunOutput> {
    const bin = findBinary(["pi"], { ...process.env, ...spec.env }) ?? "pi";
    const args = ["--mode", "json"];
    if (spec.model && !hasFlag(spec.flags, "--model")) args.push("--model", spec.model);
    // Trust project resources (AGENTS.md is always read; .pi/settings, skills and extensions need trust).
    if (!hasFlag(spec.flags, "--approve", "-a", "--no-approve", "-na")) args.push("--approve");
    args.push(...spec.flags, spec.instruction);
    let sessionId: string | undefined;
    let usage: Usage | undefined;
    const onLine = jsonLines((o) => {
      if (o.type === "session") sessionId ??= str(o.id);
      if (o.type === "message_end" && get(o, "message", "role") === "assistant") usage = addUsage(usage, piUsage(get(o, "message", "usage")));
    });
    const r = await spawnAgent({ bin, args, cwd: spec.cwd, stdoutFile: spec.stdoutFile, env: runEnv(spec, { PI_SKIP_VERSION_CHECK: "1" }), timeoutMs: spec.timeoutMs, onLine });
    return toRunOutput(r, sessionId, usage);
  },
  harnessFiles() {
    return {
      project: ["AGENTS.md", "AGENTS.override.md", "CLAUDE.md", ".pi/settings.json", ".pi/SYSTEM.md", ".pi/APPEND_SYSTEM.md", ".pi/mcp.json", ".pi/prompts/**", ".pi/skills/**", ".pi/extensions/**", ".agents/skills/**"],
      user: [
        "~/.pi/agent/AGENTS.md",
        "~/.pi/agent/AGENTS.override.md",
        "~/.pi/agent/SYSTEM.md",
        "~/.pi/agent/APPEND_SYSTEM.md",
        "~/.pi/agent/settings.json",
        "~/.pi/agent/models.json",
        "~/.pi/agent/prompts/**",
        "~/.pi/agent/skills/**",
        "~/.pi/agent/extensions/**",
        "~/.agents/skills/**",
      ],
    };
  },
  async overlay(_bundle: HarnessBundle, runDir: string) {
    const h = overlayHome(runDir);
    const agentDir = join(h, ".pi", "agent");
    // Keep the user's provider logins working inside the isolated agent dir.
    copyPrivate(join(piAgentDir(), "auth.json"), join(agentDir, "auth.json"));
    return {
      env: { PI_CODING_AGENT_DIR: agentDir, PI_CODING_AGENT_SESSION_DIR: join(runDir, "pi-sessions"), PI_SKIP_VERSION_CHECK: "1" },
      flags: [],
    };
  },
};
