// Pi coding agent (pi.dev; npm @earendil-works/pi-coding-agent, formerly @mariozechner/…).
// Tier A: TypeScript extension + JSONL session files + `--mode json` headless.
//
// Verified against pi-coding-agent 1.5.0 docs and dist/core/extensions/types.d.ts:
// - Extensions: $PI_CODING_AGENT_DIR/extensions/*.ts (default ~/.pi/agent/extensions) and
//   .pi/extensions/*.ts (project; skipped headless unless trusted or `--approve`).
//   `export default function (pi) { pi.on(event, (e, ctx) => …) }`, loaded via jiti in Node.
// - We listen only to notification events (no `input`/`tool_call` request handlers, so we
//   can never block or rewrite anything): session_start, message_end, tool_execution_start,
//   tool_execution_end {toolCallId,toolName,result,isError,durationMs}, session_compact,
//   model_select, agent_settled {aborted} (true end of a run), session_shutdown.
//   tool_execution_end has no args, so the extension caches them from _start.
// - ctx: cwd, model {provider,id}, sessionManager.getSessionId()/getSessionFile().
// - Sessions: <agentDir>/sessions/--<cwd with /\: → ->--/<ts>_<id>.jsonl, v3 tree:
//   header {type:"session",version,id,timestamp,cwd}, then entries {type,id,parentId,timestamp}
//   with type "message" (message.role user|assistant|toolResult|bashExecution|…; assistant has
//   content [text|thinking|toolCall{id,name,arguments}], usage{input,output,cacheRead,cacheWrite,
//   cost{total}}, model, provider, stopReason), "compaction", "model_change", ….
// - Pi has no built-in subagents.
