// Amp (ampcode.com). Tier A via a TypeScript plugin (Amp runs plugins with Bun).
//
// Verified against ampcode.com/docs/plugin-api (2026-11):
// - Plugins: `$XDG_CONFIG_HOME/amp/plugins/*.ts` (user, fallback ~/.config/amp/plugins) and
//   `.amp/plugins/*.ts` (project). No opt-in marker or env var is needed; files there load.
// - Events: session.start {thread}, agent.start {thread,message,id}, tool.call (a REQUEST: the
//   handler decides allow/reject), tool.result {toolUseID,tool,input,status,error?,output?},
//   agent.end {thread,message,id,status,messages[]} with assistant `usage{model,inputTokens,…}`,
//   changes.prompt. Payloads carry no cwd; amp.system.workspaceRoot (a file URI) does.
// - We never subscribe to tool.call: returning `allow` could override a permissions plugin
//   (handler order across plugins is undefined). tool.result carries the input, so tool.start
//   is synthesized from it.
// - Threads are stored server-side; there is no documented local transcript, so no backfill.
// - Headless: `amp -x "<prompt>" --stream-json` (Claude-Code-compatible stream: system/init
//   session_id = thread id, assistant/user, result{usage,duration_ms,is_error}). No cost field.
//   `--plugin-ready-timeout <s>` makes -x wait for plugins (else agent.* events can be skipped).
