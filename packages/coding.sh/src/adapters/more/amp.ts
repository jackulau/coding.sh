const ID = "amp";
const MARKER = "@codingsh-amp-plugin";
const PLUGIN_FILE = "coding-sh.ts";
const DIAL = new Set(["low", "medium", "high", "ultra"]);
/** Amp tools that run a subagent. */
const SUBAGENT_TOOLS = new Set(["Task", "oracle", "librarian", "finder", "codebase_search_agent"]);

export function ampConfigDir(env: NodeJS.ProcessEnv = process.env): string {
  return join(xdg("config", env), "amp");
}

export function ampPluginPath(opts: { scope: "user" | "project"; projectDir?: string | undefined }, env: NodeJS.ProcessEnv = process.env): string {
  if (opts.scope === "project") return join(opts.projectDir ?? process.cwd(), ".amp", "plugins", PLUGIN_FILE);
  return join(ampConfigDir(env), "plugins", PLUGIN_FILE);
}

/**
 * The plugin source. It forwards events to the shared hook (`node <hook.mjs> amp <event>`,
 * payload on stdin) and returns nothing, so it never changes Amp's behaviour. Node is
 * resolved at install time (`node` on PATH, else the node running coding.sh; see
 * resolveNodePath), with plain `node` as the runtime fallback.
 */
export function ampPluginSource(hookCommand: string, nodePath: string = resolveNodePath()): string {
  return `// ${MARKER} — generated by coding.sh; \`coding.sh uninstall amp\` removes it.
// Forwards Amp plugin events to the local coding.sh spool. Records only; never blocks or modifies.
import { spawn } from "node:child_process";
import { fileURLToPath } from "node:url";

const HOOK = ${JSON.stringify(hookCommand)};
const NODE = ${JSON.stringify(nodePath)};

export const description = "coding.sh: records prompts, tool calls and results to ~/.coding.sh (local only).";

export default function (amp: any) {
	let cwd: string | undefined;
	try {
		const root = amp?.system?.workspaceRoot;
		if (root) cwd = amp.helpers?.filePathFromURI ? amp.helpers.filePathFromURI(root) : fileURLToPath(String(root));
	} catch {
		// A POSIX URI (file:///work/x) on Windows: keep the path as written.
		try {
			cwd = fileURLToPath(String(amp.system.workspaceRoot), { windows: false });
		} catch {}
	}
	const send = (event: string, payload: unknown): Promise<void> =>
		new Promise((resolve) => {
			const body = JSON.stringify({ ...(payload as object), hook_event_name: event, cwd, ts: Date.now() });
			const go = (bin: string, retry: boolean) => {
				try {
					const child = spawn(bin, [HOOK, "amp", event], { stdio: ["pipe", "ignore", "ignore"], env: process.env });
					child.on("error", () => (retry ? go("node", false) : resolve()));
					child.on("close", () => resolve());
					child.stdin?.on("error", () => {});
					child.stdin?.end(body);
				} catch {
					if (retry) go("node", false);
					else resolve();
				}
			};
			go(NODE, true);
			const t = setTimeout(resolve, 3000);
			(t as any)?.unref?.();
		});
	amp.on("session.start", (e: unknown) => {
		void send("session.start", e);
	});
	amp.on("agent.start", (e: unknown) => {
		void send("agent.start", e);
	});
	amp.on("tool.result", (e: unknown) => {
		void send("tool.result", e);
	});
	// Awaited so the last events are flushed before \`amp -x\` exits.
	amp.on("agent.end", async (e: unknown) => {
		await send("agent.end", e);
	});
}
`;
}

function isOurPlugin(text: string | undefined): boolean {
  return !!text && text.includes(MARKER);
}

/** Map one Amp thread message (from agent.end) to events. */
async function emitThreadMessage(em: Emitter, ctx: NormalizeContext, m: Json): Promise<string | undefined> {
  if (m.role !== "assistant") return undefined;
  const ts = toMs(m.createdAt);
  const extra = ts ? { ts } : {};
  const blocks = Array.isArray(m.content) ? m.content.filter(isObj) : [];
  const text = blocks
    .filter((b) => b.type === "text" && typeof b.text === "string")
    .map((b) => b.text as string)
    .join("\n")
    .trim();
  const u = isObj(m.usage) ? m.usage : undefined;
  const model = str(u?.model);
  const usage = usageFrom(u ? { inputTokens: u.inputTokens, outputTokens: u.outputTokens, cacheReadTokens: u.cacheReadInputTokens, cacheWriteTokens: u.cacheCreationInputTokens } : undefined);
  if (u) em.push("llm.call", { responseModel: model, stopReason: str(m.stopReason), ok: m.stopReason !== "cancelled", messageId: str(m.id) }, { ...extra, ...(model ? { model } : {}), ...(usage ? { usage } : {}) });
  if (text) await emitText(em, ctx, "assistant.message", text, { ...extra, ...(model ? { model } : {}) });
  return model;
}

export async function normalizeAmp(line: SpoolLine, ctx: NormalizeContext): Promise<AgentEvent[]> {
  // Our plugin tags every payload with hook_event_name; Amp's "session.start" must not route to the wrapper.
  if (isWrapperEvent(line.event) && !(isObj(line.raw) && typeof line.raw.hook_event_name === "string")) return normalizeWrapperLine(line, ctx);
  const raw: Json = isObj(line.raw) ? line.raw : {};
  const sessionId = str(get(raw, "thread", "id")) ?? str(raw.threadId) ?? `amp-unknown-${line.ppid ?? line.pid}`;
  const cwd = str(raw.cwd) ?? line.cwd;
  const ts = toMs(raw.ts) ?? line.ts;
  const ev = str(raw.hook_event_name) ?? line.event;
  const turnId = ev === "agent.start" || ev === "agent.end" ? str(raw.id) : undefined;
  const em = new Emitter(ctx, { agent: ID, sessionId, ts, cwd, runId: line.runId, turnId }, spoolIdParts(line, sessionId, ctx));
  switch (ev) {
    case "session.start":
      em.push("session.start", { threadId: sessionId, source: "plugin" });
      break;
    case "agent.start": {
      const text = str(raw.message);
      if (text) await emitText(em, ctx, "user.message", text, {});
      break;
    }
    case "tool.call": {
      const tool = str(raw.tool) ?? "unknown";
      await emitToolStart(em, ctx, tool, str(raw.toolUseID), raw.input);
      break;
    }
    case "tool.result": {
      const tool = str(raw.tool) ?? "unknown";
      const id = str(raw.toolUseID);
      await emitToolStart(em, ctx, tool, id, raw.input);
      const status = str(raw.status) ?? "done";
      const sub = SUBAGENT_TOOLS.has(tool) && id ? id : undefined;
      // Subagent tools (Task, oracle, librarian) run their own agent loop; the plugin only sees the
      // call and its result, so the subagent spans the tool call.
      if (sub) em.push("subagent.start", { subagentId: sub, type: tool, description: str(get(raw, "input", "description")) }, { subagentId: sub });
      await emitToolEnd(em, ctx, { tool, toolUseId: id, input: raw.input, output: raw.output ?? raw.error, ok: status === "done", error: status === "done" ? undefined : (str(raw.error) ?? status) }, cwd);
      if (sub) em.push("subagent.end", { subagentId: sub, type: tool, ok: status === "done" }, { subagentId: sub });
      break;
    }
    case "agent.end": {
      let model: string | undefined;
      let usage: Usage | undefined;
      const msgs = Array.isArray(raw.messages) ? raw.messages.filter(isObj) : [];
      for (const m of msgs) {
        model = (await emitThreadMessage(em, ctx, m)) ?? model;
        const u = isObj(m.usage) ? m.usage : undefined;
        if (u) usage = addUsage(usage, { inputTokens: num(u.inputTokens), outputTokens: num(u.outputTokens), cacheReadTokens: num(u.cacheReadInputTokens), cacheWriteTokens: num(u.cacheCreationInputTokens) } as Usage);
      }
      const status = str(raw.status) ?? "done";
      if (status === "error") em.push("error", { message: "agent turn ended with an error", status });
      // Usage already sits on the llm.call events; turn.end carries no usage to avoid double counting.
      em.push("turn.end", { status, messages: msgs.length, model, inputTokens: usage?.inputTokens, outputTokens: usage?.outputTokens }, model ? { model } : {});
      break;
    }
    case "changes.prompt":
      em.push("notification", { kind: "changes.prompt", workflow: str(raw.workflow) });
      break;
    default:
      em.push("notification", { kind: ev });
  }
  return attachRaw(em.events, await rawBlob(ctx, line.raw));
}

/** Parse Amp's Claude-compatible stream-json into session id + usage. */
export function ampStreamParser(): { onLine: (l: string) => void; sessionId: () => string | undefined; usage: () => Usage | undefined } {
  let sessionId: string | undefined;
  let resultUsage: Usage | undefined;
  let summed: Usage | undefined;
  const onLine = jsonLines((o) => {
    sessionId ??= str(o.session_id);
    if (o.type === "assistant" && !o.parent_tool_use_id) summed = addUsage(summed, usageFrom(get(o, "message", "usage")));
    if (o.type === "result") {
      resultUsage = usageFrom(o.usage) ?? resultUsage;
      const cost = num(o.total_cost_usd);
      if (cost !== undefined) resultUsage = { ...(resultUsage ?? {}), costUsd: cost };
    }
  });
  return { onLine, sessionId: () => sessionId, usage: () => resultUsage ?? summed };
}

export const ampAdapter: Adapter = {
  id: ID,
  displayName: "Amp",
  tier: "A",
  async detect(): Promise<DetectResult> {
    const binary = findBinary(["amp"]);
    const dir = ampConfigDir();
    const r: DetectResult = { installed: !!binary || existsSync(dir), hooked: isOurPlugin(readText(ampPluginPath({ scope: "user" }))) };
    if (binary) {
      r.binary = binary;
      const v = (await binVersion(binary, ["--version"])) ?? (await binVersion(binary, ["version"]));
      if (v) r.version = v;
    }
    if (existsSync(dir)) r.configDir = dir;
    r.notes = ["Threads live on Amp's servers: live capture only (no local transcript backfill)."];
    return r;
  },
  async install(opts: InstallOpts): Promise<FileChange[]> {
    const path = ampPluginPath(opts);
    const before = readText(path);
    if (before !== undefined && !isOurPlugin(before)) throw new Error(`${path} exists and was not written by coding.sh; refusing to overwrite it`);
    const after = ampPluginSource(opts.hookCommand, resolveNodePath(process.env));
    return applyWrites(ID, [{ path, before, after, summary: `${before ? "update" : "add"} Amp plugin that records events to coding.sh`, mode: 0o644 }], opts.dryRun);
  },
  async uninstall(opts): Promise<FileChange[]> {
    const path = ampPluginPath(opts);
    const before = readText(path);
    if (!isOurPlugin(before)) return [];
    return applyWrites(ID, [{ path, before, after: undefined, summary: "remove the coding.sh Amp plugin" }], opts.dryRun);
  },
  normalize: normalizeAmp,
  async run(spec: RunSpec): Promise<AgentRunOutput> {
    const bin = findBinary(["amp"], { ...process.env, ...spec.env }) ?? "amp";
    const args = ["-x", spec.instruction, "--stream-json"];
    let note = "";
    if (spec.model && !hasFlag(spec.flags, "--mode", "-m")) {
      if (DIAL.has(spec.model)) args.push("--mode", spec.model);
      else note = `amp: model "${spec.model}" ignored (Amp picks models itself; use --mode low|medium|high|ultra)\n`;
    }
    if (isOurPlugin(readText(ampPluginPath({ scope: "user" }))) && !hasFlag(spec.flags, "--plugin-ready-timeout")) args.push("--plugin-ready-timeout", "10");
    args.push(...spec.flags);
    const p = ampStreamParser();
    const r = await spawnAgent({ bin, args, cwd: spec.cwd, env: runEnv(spec, { AMP_SKIP_UPDATE_CHECK: "1" }), timeoutMs: spec.timeoutMs, onLine: p.onLine });
    if (note) r.stderrTail = note + r.stderrTail;
    return toRunOutput(r, p.sessionId(), p.usage());
  },
  harnessFiles() {
    return {
      project: ["AGENTS.md", "AGENT.md", "CLAUDE.md", "**/AGENTS.md", ".amp/settings.json", ".amp/settings.jsonc", ".amp/plugins/**", ".agents/skills/**", ".claude/skills/**"],
      user: [
        "~/.config/amp/AGENTS.md",
        "~/.config/AGENTS.md",
        "~/.config/amp/settings.json",
        "~/.config/amp/settings.jsonc",
        "~/.config/amp/plugins/**",
        "~/.config/amp/skills/**",
        "~/.agents/skills/**",
        "~/.config/agents/skills/**",
      ],
    };
  },
  async overlay(bundle: HarnessBundle, runDir: string) {
    // Amp keeps auth outside the settings file, so we only swap the settings file
    // (bundle-provided, materialized under <runDir>/home) and leave XDG alone.
    const flags: string[] = [];
    for (const key of ["~/.config/amp/settings.json", "~/.config/amp/settings.jsonc"]) {
      if (bundle.files[key]) {
        flags.push("--settings-file", join(runDir, "home", key.slice(2)));
        break;
      }
    }
    return { env: { AMP_SKIP_UPDATE_CHECK: "1" }, flags };
  },
};
