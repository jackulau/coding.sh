// Bundles the CLI, the hook, and the schema into dependency-free ESM files.
// The published package has zero runtime dependencies: `npx coding.sh` downloads
// one tarball and starts immediately. Used by build.mjs and by the CLI tests
// (which bundle into a temp dir so they never depend on a stale dist/).
import { build } from "esbuild";
import { chmodSync, copyFileSync, mkdirSync, readFileSync, rmSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

/** @param {string} outdir absolute or package-relative output directory */
export async function bundle(outdir = "dist") {
  const out = resolve(root, outdir);
  rmSync(out, { recursive: true, force: true });
  mkdirSync(out, { recursive: true });
  const pkg = JSON.parse(readFileSync(join(root, "package.json"), "utf8"));
  const common = {
    absWorkingDir: root,
    bundle: true,
    platform: "node",
    format: "esm",
    target: "node22",
    sourcemap: false,
    legalComments: "none",
    logLevel: "warning",
    outExtension: { ".js": ".mjs" },
    outdir: out,
    // node: builtins stay external automatically on platform=node.
  };
  const [cliBuild] = await Promise.all([
    build({
      ...common,
      entryPoints: { cli: "src/cli/main.ts" },
      metafile: true,
      // Command modules load through dynamic import() after dispatch; splitting
      // keeps them out of cli.mjs so `--help` parses a few KB, not the whole
      // tool. Chunks sit next to cli.mjs so `new URL("./hook.mjs", import.meta.url)`
      // still resolves from any of them.
      splitting: true,
      chunkNames: "chunk-[hash]",
      define: { __CODING_SH_VERSION__: JSON.stringify(pkg.version) },
      banner: { js: "#!/usr/bin/env node" },
      loader: { ".html": "text", ".css": "text" },
    }),
    build({ ...common, entryPoints: { hook: "src/spool/hook.ts" }, banner: { js: "#!/usr/bin/env node" }, minify: true }),
    build({ ...common, entryPoints: { schema: "src/schema/index.ts" } }),
    // Store plugin API (`coding.sh/store`, `coding.sh/store/conformance`):
    // plugins bundle these helpers in, so they load next to any install.
    build({ ...common, entryPoints: { store: "src/store/plugin-api.ts", "store-conformance": "src/store/conformance.ts" } }),
    // eve eval reporter (`coding.sh/eve`): codingShReporter, no other code.
    build({ ...common, entryPoints: { eve: "src/integrations/eve/reporter.ts" } }),
    // Serverless ingest (`coding.sh/server`): createFetchHandler, serve's ingest routes as a fetch handler.
    build({ ...common, entryPoints: { server: "src/server/index.ts" } }),
    // Judge library (`coding.sh/judge`): pairedDiscrimination, createWasteJudge and the providers they call.
    build({ ...common, entryPoints: { judge: "src/judge/lib.ts" } }),
  ]);
  chmodSync(join(out, "cli.mjs"), 0o755);
  chmodSync(join(out, "hook.mjs"), 0o755);
  // The POSIX sh fast path agents run outside Windows; it hands what it does not cover to hook.mjs.
  copyFileSync(join(root, "src", "spool", "hook.sh"), join(out, "hook.sh"));
  chmodSync(join(out, "hook.sh"), 0o755);
  // The trace format's JSON Schema (`coding.sh/schema.json`), generated by scripts/json-schema.ts.
  copyFileSync(join(root, "src", "schema", "trace.schema.json"), join(out, "schema.json"));
  // The source files esbuild put in cli.mjs itself (not in a chunk), so tests can check what `--help` loads.
  const entry = Object.entries(cliBuild.metafile.outputs).find(([file]) => file.endsWith("/cli.mjs") || file === "cli.mjs");
  const cliInputs = entry ? Object.keys(entry[1].inputs) : [];
  return { cli: join(out, "cli.mjs"), cliInputs, hook: join(out, "hook.mjs"), hookSh: join(out, "hook.sh"), schema: join(out, "schema.mjs"), store: join(out, "store.mjs") };
}
