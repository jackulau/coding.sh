#!/bin/sh
# Writes the compose stack's secrets to .env at the repo root, with mode 600, and prints no secret.
#   deploy/compose/gen-env.sh            keep an existing .env (Postgres keeps its first password)
#   deploy/compose/gen-env.sh --force    regenerate; run `docker compose down -v` first
# ENV_FILE overrides the output path.
set -eu
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
OUT=${ENV_FILE:-$ROOT/.env}
NAMES="POSTGRES_PASSWORD MINIO_ROOT_USER MINIO_ROOT_PASSWORD INGEST_KEY_DEMO INGEST_KEY_FLOOD READ_KEY"

if [ -f "$OUT" ] && [ "${1:-}" != "--force" ]; then
  echo "kept $OUT (--force regenerates it)"
  exit 0
fi

hex() { od -An -N"$1" -tx1 /dev/urandom | tr -d ' \n'; }
# csh_<ik|rk>_ + 32 random bytes in base64url, the format `coding.sh serve keygen` prints.
key() { printf 'csh_%s_%s' "$1" "$(head -c 32 /dev/urandom | base64 | tr '+/' '-_' | tr -d '=\n')"; }

umask 077
tmp="$OUT.tmp.$$"
trap 'rm -f "$tmp"' EXIT
{
  echo "# coding.sh compose secrets, generated by deploy/compose/gen-env.sh. Do not commit."
  echo "POSTGRES_PASSWORD=$(hex 24)"
  echo "MINIO_ROOT_USER=coding$(hex 4)"
  echo "MINIO_ROOT_PASSWORD=$(hex 24)"
  echo "INGEST_KEY_DEMO=$(key ik)"
  echo "INGEST_KEY_FLOOD=$(key ik)"
  echo "READ_KEY=$(key rk)"
} >"$tmp"
chmod 600 "$tmp"
mv "$tmp" "$OUT"
trap - EXIT
echo "wrote $OUT (mode 600): $NAMES"
